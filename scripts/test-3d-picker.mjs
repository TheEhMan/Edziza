import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { EARTH_ANALOGS, getTarget } from '../src/analogData.js';
import { rankAnalogs } from '../src/analogRanking.js';
import { DEFAULT_WEIGHTS } from '../src/analogData.js';
import { normalizeLongitude, sphericalDistanceKm, nearestReferenceSite } from '../src/planetarySelection.js';
import { sampleMoonHeightKm } from '../src/moonTopography.js';

assert.equal(normalizeLongitude(383.47314), 23.47314);
assert.equal(normalizeLongitude(-190), 170);
assert.ok(Math.abs(sphericalDistanceKm({lat:0,lon:179}, {lat:0,lon:-179}, 'moon') - 60.65) < 1);
const apollo = nearestReferenceSite('moon', 0.67416, 23.47314);
assert.equal(apollo.referenceId, 'apollo11');
assert.equal(apollo.distanceKm, 0);
assert.equal(apollo.inResearchVicinity, true);
const elysium = nearestReferenceSite('mars', 24.74, 146.9);
assert.equal(elysium.referenceId, 'elysium');
assert.equal(elysium.distanceKm, 0);
const farside = nearestReferenceSite('moon', 0, 180);
assert.equal(farside.inResearchVicinity, false);
assert.ok(farside.distanceKm > 1000);
assert.throws(() => nearestReferenceSite('mars', 91, 150.2), /Invalid planetary/);
const lunarGrid = { width: 4, height: 2, values: Float32Array.from([0, 1, 2, 3, 4, 5, 6, 7]) };
assert.equal(sampleMoonHeightKm(lunarGrid, 0, 0), 6);
assert.equal(sampleMoonHeightKm(null, 0, 0), null);
assert.equal(sampleMoonHeightKm(lunarGrid, NaN, 0), null);
const map = await readFile(new URL('../src/EarthMap.jsx', import.meta.url), 'utf8');
assert.match(map, /EARTH_ANALOGS\.map\(site => \[site\.id/);
assert.ok(EARTH_ANALOGS.some(site => site.id === 'cratersmoon'));
assert.ok(!EARTH_ANALOGS.some(site => /snowshoe|desolation/i.test(site.name)));

const mars = await readFile(new URL('../src/MarsScene.jsx', import.meta.url), 'utf8');
const moon = await readFile(new URL('../src/MoonScene.jsx', import.meta.url), 'utf8');
const finder = await readFile(new URL('../src/AnalogFinder.jsx', import.meta.url), 'utf8');
for (const feature of ['onPointerDown', 'onPointerUp', 'onPick?.(lat, lon', 'getElevationAt']) assert.ok(mars.includes(feature), `Mars missing ${feature}`);
for (const feature of ['onPointerDown', 'onPointerUp', 'onPick?.(lat, lon', 'loadMoonElevationGrid', 'moonHeightRadius']) assert.ok(moon.includes(feature), `Moon missing ${feature}`);
assert.match(finder, /whole planet of Mars in 3D/);
assert.match(finder, /Outside the nearby research area: exploratory extrapolation with LOW confidence/);
assert.match(finder, /ranked/);
const globe = await readFile(new URL('../src/MarsGlobalGlobe.jsx', import.meta.url), 'utf8');
assert.match(globe, /onPick\?\.\(lat, lon/);
assert.match(globe, /MOLA MEGDR GLOBAL ELEVATION/);
assert.match(mars, /Whole Mars 3D/);
const suggested = rankAnalogs(getTarget('mars', elysium.referenceId), DEFAULT_WEIGHTS);
assert.equal(suggested[0].earth.id, 'cratersmoon');
console.log('3D selection tests passed: real location picking on Mars and Moon, spherical distances and uncertainty, NASA DEM sampling, and correct Earth map target catalogue.');
