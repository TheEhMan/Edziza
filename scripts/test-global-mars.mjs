import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { MARS_DEM_BYTES, MARS_GLOBAL_WIDTH, MARS_GLOBAL_HEIGHT, readMolaMegdr, sampleMolaMegdr, MARS_VIKING_TILES } from '../src/marsGlobalData.js';
import { rankAnalogs } from '../src/analogRanking.js';
import { getTarget, DEFAULT_WEIGHTS } from '../src/analogData.js';

const raw = new ArrayBuffer(MARS_DEM_BYTES);
const view = new DataView(raw);
// Test big-endian signed heights, dateline behavior and correct latitude row.
view.setInt16(0, -1200, false);
view.setInt16(2, -1600, false);
view.setInt16((MARS_GLOBAL_WIDTH-1)*2, -2000, false);
view.setInt16(MARS_GLOBAL_WIDTH*2, -2200, false);
view.setInt16(MARS_DEM_BYTES-2, 2300, false);
const data = readMolaMegdr(raw);
assert.equal(data.width, 1440);
assert.equal(data.height, 720);
assert.equal(sampleMolaMegdr(data, 90, 0), -1200);
assert.equal(sampleMolaMegdr(data, 90, 0.25), -1600);
assert.equal(sampleMolaMegdr(data, 90, 359.75), -2000);
assert.equal(sampleMolaMegdr(data, 90, -0.25), -2000);
assert.equal(sampleMolaMegdr(data, -90, 359.75), 2300);
assert.equal(sampleMolaMegdr(data, -95, 30), null);
assert.throws(() => readMolaMegdr(new ArrayBuffer(200)), /expected/);
assert.match(MARS_VIKING_TILES, /Mars_Viking_MDIM21/);
const globalScene = await readFile(new URL('../src/MarsGlobalGlobe.jsx', import.meta.url), 'utf8');
assert.match(globalScene, /frameloop="demand"/);
assert.match(globalScene, /manifest.json/);
assert.match(globalScene, /onPointerUp/);
const moonTiles = await readFile(new URL('../src/MoonTiledLayer.jsx', import.meta.url), 'utf8');
assert.match(moonTiles, /LRO_WAC_Mosaic_Global_303ppd_v02/);
assert.match(moonTiles, /viewportWidth/);
assert.match(moonTiles, /mapWidth\*view.zoom/);
const moon = await readFile(new URL('../src/MoonScene.jsx', import.meta.url), 'utf8');
assert.match(moon, /LUNAR_RELIEF_EXAGGERATION = 1\.5/);
assert.doesNotMatch(moon, /relief exaggerated 22×/);
const app = await readFile(new URL('../src/App.jsx', import.meta.url), 'utf8');
assert.match(app, /only one interactive WebGL map runs at a time/);
const ranked = rankAnalogs(getTarget('mars', 'elysium'), DEFAULT_WEIGHTS);
assert.equal(ranked[0].earth.name, 'Craters of the Moon');
assert.ok(ranked[0].score > 55 && ranked[0].score < 90, 'Domain task-fit must be readable and remain non-certifying');
console.log('Full Mars globe raster parser, NASA tile requests, relief, lazy compare view and evidence penalties verified.');
